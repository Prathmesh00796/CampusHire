const parsedStudents = [];

for (const line of lines) {
  const trimmed = line.trim();
  if (!trimmed) continue;

  // Format: [SR.NO] [PRN] [NAME...] [BRANCH...] [CGPA]
  // Branches are:
  // - "COMPUTER SCIENCE AND ENGINEERING"
  // - "AI & DATA SCIENCE"
  // - "CSE AI & ML"
  
  let branch = '';
  let branchIdx = -1;
  
  if (trimmed.includes('COMPUTER SCIENCE AND ENGINEERING')) {
    branch = 'Computer Science and Engineering';
    branchIdx = trimmed.indexOf('COMPUTER SCIENCE AND ENGINEERING');
  } else if (trimmed.includes('AI & DATA SCIENCE')) {
    branch = 'AI & Data Science';
    branchIdx = trimmed.indexOf('AI & DATA SCIENCE');
  } else if (trimmed.includes('CSE AI & ML')) {
    branch = 'CSE (AI & ML)';
    branchIdx = trimmed.indexOf('CSE AI & ML');
  }

  if (branchIdx !== -1) {
    const beforeBranch = trimmed.substring(0, branchIdx).trim();
    const afterBranch = trimmed.substring(branchIdx + (
      branch === 'Computer Science and Engineering' ? 'COMPUTER SCIENCE AND ENGINEERING'.length :
      branch === 'AI & Data Science' ? 'AI & DATA SCIENCE'.length :
      'CSE AI & ML'.length
    )).trim();

    const beforeTokens = beforeBranch.split(/\s+/);
    const srNo = beforeTokens[0];
    const prn = beforeTokens[1].toUpperCase();
    const fullName = beforeTokens.slice(2).join(' ');

    const cgpaMatch = afterBranch.match(/\d+(\.\d+)?/);
    const cgpa = cgpaMatch ? parseFloat(cgpaMatch[0]) : 7.0;

    parsedStudents.push({
      srNo: parseInt(srNo),
      prn,
      fullName,
      branch,
      cgpa
    });
  }
}

